/// The largest `N` accepted by `--top-ports` (the length of [`TOP_PORTS`]).
pub const MAX_TOP_PORTS: usize = TOP_PORTS.len();

/// Named port sets for quick recon, selected with `--ports <name>`.
///
/// Each set is a small, curated group of ports for a common surface. Names are
/// matched case-insensitively.
pub static NAMED_PORT_SETS: &[(&str, &[u16])] = &[
    ("web", &[80, 443, 8080, 8443, 8000, 8008, 8888]),
    ("mail", &[25, 110, 143, 465, 587, 993, 995]),
    ("db", &[1433, 1521, 3306, 5432, 6379, 9042, 11211, 27017]),
    ("remote", &[22, 23, 3389, 5900, 5985, 5986]),
    ("windows", &[135, 139, 445, 3389, 5985, 5986]),
];

/// Return the first `n` entries of [`TOP_PORTS`], or an error when `n` is 0 or
/// exceeds [`MAX_TOP_PORTS`].
pub fn top_ports(n: usize) -> Result<Vec<u16>, String> {
    if n == 0 {
        return Err("--top-ports must be at least 1".to_string());
    }
    if n > MAX_TOP_PORTS {
        return Err(format!(
            "--top-ports supports at most {} ports (requested {})",
            MAX_TOP_PORTS, n
        ));
    }
    Ok(TOP_PORTS[..n].to_vec())
}

/// Resolve a named port set (case-insensitive) to its ports, or an error that
/// lists the available names.
pub fn named_port_set(name: &str) -> Result<Vec<u16>, String> {
    let lower = name.to_ascii_lowercase();
    NAMED_PORT_SETS
        .iter()
        .find(|(n, _)| *n == lower)
        .map(|(_, ports)| ports.to_vec())
        .ok_or_else(|| {
            let names: Vec<&str> = NAMED_PORT_SETS.iter().map(|(n, _)| *n).collect();
            format!(
                "Unknown port set '{}'; available: {}",
                name,
                names.join(", ")
            )
        })
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn top_ports_list_is_exactly_1000_unique_ports() {
        assert_eq!(TOP_PORTS.len(), 1000);
        let unique: HashSet<u16> = TOP_PORTS.iter().copied().collect();
        assert_eq!(unique.len(), 1000, "TOP_PORTS must not contain duplicates");
    }

    #[test]
    fn common_ports_rank_near_the_top() {
        let top10: HashSet<u16> = TOP_PORTS[..10].iter().copied().collect();
        for p in [80u16, 443, 22] {
            assert!(top10.contains(&p), "port {} should be in the top 10", p);
        }
    }

    #[test]
    fn top_ports_returns_requested_count() {
        assert_eq!(top_ports(100).unwrap().len(), 100);
        assert_eq!(top_ports(1000).unwrap().len(), 1000);
        assert_eq!(top_ports(1).unwrap(), vec![TOP_PORTS[0]]);
    }

    #[test]
    fn top_ports_rejects_zero_and_overflow() {
        assert!(top_ports(0).is_err());
        assert!(top_ports(MAX_TOP_PORTS + 1).is_err());
    }

    #[test]
    fn named_sets_resolve_case_insensitively() {
        assert_eq!(
            named_port_set("web").unwrap(),
            vec![80, 443, 8080, 8443, 8000, 8008, 8888]
        );
        assert_eq!(
            named_port_set("WEB").unwrap(),
            named_port_set("web").unwrap()
        );
        assert!(named_port_set("nope").is_err());
    }
}
